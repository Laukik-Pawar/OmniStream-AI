
import re
import logging

import numpy as np

from sklearn.feature_extraction.text import (
    TfidfVectorizer,
    ENGLISH_STOP_WORDS
)
from sklearn.metrics.pairwise import cosine_similarity

from app.services.recommendation_engine import _embed_texts


logger = logging.getLogger(__name__)


CUSTOM_STOPWORDS = {
    "guys", "finally", "just", "really",
    "viral", "trending", "video", "shorts",
    "youtubeshorts", "official", "please",
    "ama", "think", "hope", "today",
    "thing", "things", "damn", "available",
    "viralvideo", "subscribe", "follow",
    "click", "link", "deleted", "removed",
    "comment", "comments", "provided",
    "auto-generated", "youtube", "reddit",
    "sponsored", "s", "m", "t"
}

STOPWORDS = set(ENGLISH_STOP_WORDS) | CUSTOM_STOPWORDS


BOILERPLATE_PATTERNS = [
    r"this comment (?:was|has been) deleted[^\n]*",
    r"this post (?:was|has been) removed[^\n]*",
    r"provided to youtube by[^\n]*",
    r"auto-generated by youtube[^\n]*",
    r"subscribe to[^\n]*",
    r"follow me on[^\n]*",
    r"for business inquiries[^\n]*",
    r"all rights reserved[^\n]*",
    r"no description available",
    r"link post\s*-\s*no description",
    r"no description"
]


def clean_interest_text(text):
    """Remove irrelevant metadata while preserving context."""

    text = str(text or "")

    for pattern in BOILERPLATE_PATTERNS:
        text = re.sub(
            pattern,
            " ",
            text,
            flags=re.IGNORECASE
        )

    text = re.sub(r"https?://\S+", " ", text)
    text = re.sub(r"@\w+", " ", text)

    # Preserve hashtag words.
    text = re.sub(r"#(?=\w)", " ", text)

    # Preserve Unicode characters and certification codes.
    text = re.sub(r"[^\w\s\-.,!?;:|।]", " ", text)

    text = re.sub(r"\s+", " ", text)

    return text.strip()


def phrase_analyzer(text):
    """
    Generate contiguous phrases without crossing
    sentence or metadata boundaries.
    """

    phrases = []

    segments = re.split(r"[.!?;:|।\n]+", text.lower())

    for segment in segments:

        tokens = re.findall(
            r"(?u)\b[\w]+(?:-[\w]+)*\b",
            segment
        )

        for start in range(len(tokens)):

            for size in range(1, 5):

                words = tokens[start:start + size]

                if len(words) != size:
                    continue

                # Do not generate phrases containing filler.
                if any(word in STOPWORDS for word in words):
                    continue

                if all(word.isnumeric() for word in words):
                    continue

                phrase = " ".join(words)

                if len(phrase) >= 3:
                    phrases.append(phrase)

    return phrases


def is_redundant(phrase, selected):
    """Detect duplicate and heavily overlapping phrases."""

    words = set(phrase.split())

    for existing in selected:

        existing_words = set(existing.split())

        if words.issubset(existing_words):
            return True

        if existing_words.issubset(words):
            return True

        union = words | existing_words

        overlap = len(words & existing_words) / len(union)

        if overlap >= 0.6:
            return True

    return False


def extract_interests(topic_groups, top_n=5):
    """
    Extract title-prioritized interest phrases
    from semantic topic groups.
    """

    documents = []
    group_records = []

    # 1. Prepare titles and descriptions separately.
    for group in topic_groups:

        records = []

        for item in group["interactions"]:

            title = clean_interest_text(
                item.get("title")
            )

            content = clean_interest_text(
                item.get("content")
            )[:300]

            if not title and not content:
                continue

            title_index = len(documents)
            documents.append(title)

            content_index = len(documents)
            documents.append(content)

            records.append({
                "title": title,
                "content": content,
                "title_index": title_index,
                "content_index": content_index
            })

        if records:
            group_records.append((group, records))

    if not documents:
        return []

    # 2. Generate TF-IDF phrase representations.
    vectorizer = TfidfVectorizer(
        analyzer=phrase_analyzer,
        max_features=10000,
        sublinear_tf=True
    )

    try:
        matrix = vectorizer.fit_transform(documents)

    except ValueError:
        return []

    terms = vectorizer.get_feature_names_out()

    profiles = []

    # 3. Score phrases within each semantic group.
    for group, records in group_records:

        phrase_scores = {}
        title_terms = set()
        phrase_support = {}

        for record in records:

            seen_in_interaction = set()

            for index, weight in [
                (record["title_index"], 3.0),
                (record["content_index"], 1.0)
            ]:

                row = matrix.getrow(index)

                for term_index, score in zip(
                    row.indices,
                    row.data
                ):

                    phrase = terms[term_index]

                    phrase_scores[phrase] = (
                        phrase_scores.get(phrase, 0.0)
                        + float(score) * weight
                    )

                    seen_in_interaction.add(phrase)

                    if index == record["title_index"]:
                        title_terms.add(phrase)

            for phrase in seen_in_interaction:

                phrase_support[phrase] = (
                    phrase_support.get(phrase, 0) + 1
                )

        if not phrase_scores:
            continue

        # 4. Prefer recurring and specific phrases.
        for phrase in phrase_scores:

            word_count = len(phrase.split())

            specificity = 1.0 + (
                0.15 * min(word_count - 1, 3)
            )

            recurrence = 1.0 + (
                0.25 * (phrase_support[phrase] - 1)
            )

            phrase_scores[phrase] *= (
                specificity * recurrence
            )

        ranked = sorted(
            phrase_scores.items(),
            key=lambda item: item[1],
            reverse=True
        )[:40]

        candidates = [
            {
                "phrase": phrase,
                "lexical": score,
                "from_title": phrase in title_terms
            }
            for phrase, score in ranked
        ]

        # 5. Compare candidate phrases with source meaning.
        max_lexical = max(
            item["lexical"]
            for item in candidates
        )

        try:

            source_texts = [
                record["title"] or record["content"]
                for record in records
            ]

            candidate_texts = [
                item["phrase"]
                for item in candidates
            ]

            embeddings = _embed_texts(
                source_texts + candidate_texts
            )

            source_count = len(source_texts)

            similarities = cosine_similarity(
                embeddings[source_count:],
                embeddings[:source_count]
            )

            for i, item in enumerate(candidates):

                semantic = float(
                    np.clip(
                        0.6 * similarities[i].max()
                        + 0.4 * similarities[i].mean(),
                        0,
                        1
                    )
                )

                lexical = item["lexical"] / max_lexical

                title_bonus = (
                    0.1 if item["from_title"] else 0.0
                )

                item["score"] = (
                    0.6 * semantic
                    + 0.4 * lexical
                    + title_bonus
                )

        except Exception:

            logger.exception(
                "Interest semantic scoring failed."
            )

            for item in candidates:

                item["score"] = (
                    item["lexical"] / max_lexical
                )

        # 6. Select diverse, non-redundant phrases.
        candidates.sort(
            key=lambda item: item["score"],
            reverse=True
        )

        selected = []

        # Ensure the primary interest comes from a title
        # whenever a usable title phrase exists.
        primary = next(
            (
                item["phrase"]
                for item in candidates
                if item["from_title"]
            ),
            candidates[0]["phrase"]
        )

        selected.append(primary)

        for item in candidates:

            if len(selected) >= top_n:
                break

            phrase = item["phrase"]

            if is_redundant(phrase, selected):
                continue

            selected.append(phrase)

        # 7. Build the final interest profile.
        profiles.append({
            "topic": selected[0],
            "interests": selected,
            "count": group["count"],
            "sources": group["sources"],
            "confidence": group.get("confidence"),
            "titles": [
                item.get("title", "")
                for item in group["interactions"]
            ]
        })

    profiles.sort(
        key=lambda item: item["count"],
        reverse=True
    )

    return profiles
